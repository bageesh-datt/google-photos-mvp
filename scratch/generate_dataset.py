def main():
    clean_metadata = []
    for p in photos_data:
        p_copy = dict(p)
        p_copy.pop("theme_color", None)
        
        objs = p_copy.get("objects", [])
        concepts = p_copy.get("visual_concepts", [])
        desc = p_copy.get("description", "")
        event = p_copy.get("event", "")
        landmark = p_copy.get("location", {}).get("landmark", "")
        city = p_copy.get("location", {}).get("city", "")
        
        p_copy["visual_semantics"] = {
            "objects": objs,
            "visual_concepts": concepts,
            "scene": event or (concepts[0] if concepts else "outdoor"),
            "activities": [event] if event else [],
            "people_context": "family" if "family" in p_copy.get("people_relationships", []) else ("friends" if "friends" in p_copy.get("people_relationships", []) else "general"),
            "environment": f"{landmark}, {city}".strip(", "),
            "generated_description": desc
        }
        clean_metadata.append(p_copy)
        
    with open(METADATA_PATH, "w", encoding="utf-8") as f:
        json.dump(clean_metadata, f, indent=2, ensure_ascii=False)
        
    print(f"Dataset metadata updated successfully! {len(clean_metadata)} records written to {METADATA_PATH}")

if __name__ == "__main__":
    main()

